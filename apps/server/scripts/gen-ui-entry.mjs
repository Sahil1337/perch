// Writes build/ui-entry.ts, the entry `bun run compile` builds from instead of src/cli/main.ts.
//
// `bun build --compile` embeds a file only if something imports it with `{ type: "file" }`, and the
// UI is a tree of hashed filenames a new frontend build renames wholesale — so the import list is
// generated here on every compile rather than written by hand. The entry registers the resulting
// bundle paths and only then loads the CLI: a static `import "../src/cli/main.js"` is hoisted and
// would run the entire program before the map existed.
//
// Node never sees this file. It is build output (`build/` is gitignored) and it uses an import
// attribute only Bun's bundler understands; `bun run build` still compiles src/ with tsc for the
// installed-package deployment, where ui/ is a real directory next to dist/.

import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const serverDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const uiDir = path.join(serverDir, "ui");
const outFile = path.join(serverDir, "build", "ui-entry.ts");

/** Every file under ui/, as the slash-separated paths the server looks assets up by. */
function collect(dir, prefix = "") {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return []; // no UI built yet: the binary falls back to the placeholder page, same as today
  }
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...collect(path.join(dir, entry.name), rel));
    else if (entry.isFile()) files.push(rel);
  }
  return files;
}

const files = collect(uiDir);
const imports = files.map(
  (rel, i) => `import a${i} from ${JSON.stringify(`../ui/${rel}`)} with { type: "file" };`,
);
const entries = files.map((rel, i) => `  ${JSON.stringify(rel)}: a${i},`);

const source = `// Generated by scripts/gen-ui-entry.mjs on every \`bun run compile\`. Do not edit.
import { setEmbeddedUi } from "../src/util/embedded-ui.js";
${imports.join("\n")}

setEmbeddedUi({
${entries.join("\n")}
});

// Dynamic on purpose: main.js starts the CLI the moment it is evaluated, and it must not be
// evaluated until the map above is in place.
await import("../src/cli/main.js");
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, source);
console.log(`ui-entry: ${files.length} file(s) from ${path.relative(process.cwd(), uiDir)}`);
