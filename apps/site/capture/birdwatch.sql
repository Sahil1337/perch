-- Birdwatch: a small, original birding dataset for the Perch site recordings.
-- Real species and places, invented observers and checklists. Fixed dates (spring 2026), so every
-- recording is reproducible. Idempotent: drops and recreates its own objects.
--
--   createdb perch_site_demo
--   psql -d perch_site_demo -f apps/site/capture/birdwatch.sql

set client_min_messages = warning;

-- The sites are British, so dates read in their time zone whatever the server's default is; a
-- recording made on another machine shows the same days.
do $$ begin execute format('alter database %I set timezone = %L', current_database(), 'Europe/London'); end $$;

drop view if exists species_totals, checklist_summary;
drop table if exists sightings, checklists, observers, sites, species, families cascade;
drop function if exists touch_species_last_seen();

create table families (
  id serial primary key,
  name text not null unique,
  latin_name text not null unique
);

create table species (
  id serial primary key,
  common_name text not null unique,
  scientific_name text not null unique,
  family_id int not null references families (id),
  status char(2) not null check (status in ('LC', 'NT', 'VU', 'EN', 'CR')),
  migrant boolean not null default false,
  last_seen_at timestamptz
);

comment on column species.status is 'IUCN Red List category';

create table sites (
  id serial primary key,
  name text not null unique,
  region text not null,
  habitat text not null,
  lat numeric(7, 4) not null,
  lon numeric(7, 4) not null
);

create table observers (
  id serial primary key,
  name text not null,
  joined_on date not null
);

create table checklists (
  id serial primary key,
  observer_id int not null references observers (id),
  site_id int not null references sites (id),
  started_at timestamptz not null,
  duration_min int not null check (duration_min > 0)
);

create table sightings (
  id serial primary key,
  checklist_id int not null references checklists (id) on delete cascade,
  species_id int not null references species (id),
  count int not null check (count > 0),
  behaviour text,
  seen_at timestamptz not null
);

create index on checklists (site_id);
create index on sightings (checklist_id);
create index on sightings (species_id);

create function touch_species_last_seen() returns trigger
language plpgsql as $$
begin
  update species
     set last_seen_at = greatest(last_seen_at, new.seen_at)
   where id = new.species_id;
  return new;
end;
$$;

create trigger sightings_touch_species
  after insert on sightings
  for each row execute function touch_species_last_seen();

create view species_totals as
select s.id, s.common_name, f.name as family, s.status,
       count(g.id) as sightings, coalesce(sum(g.count), 0) as birds, s.last_seen_at
  from species s
  join families f on f.id = s.family_id
  left join sightings g on g.species_id = s.id
 group by s.id, f.name;

create view checklist_summary as
select c.id, o.name as observer, t.name as site, c.started_at,
       count(g.id) as species, sum(g.count) as birds
  from checklists c
  join observers o on o.id = c.observer_id
  join sites t on t.id = c.site_id
  left join sightings g on g.checklist_id = c.id
 group by c.id, o.name, t.name;

